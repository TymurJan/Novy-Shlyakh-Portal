import re

# Список літер, які є лише в російській мові
RU_LETTERS_RE = re.compile(r'[ыЫэЭъЪёЁ]')

# Популярні російські слова для детекції мови
RU_WORDS = {
    'это', 'как', 'что', 'очень', 'был', 'была', 'было', 'были', 'меня', 'мне', 
    'тебя', 'тебе', 'его', 'ее', 'ней', 'ним', 'ими', 'нет', 'даже', 'когда', 
    'только', 'после', 'если', 'или', 'чтобы', 'зачем', 'почему', 'здесь', 'сейчас'
}

# Базовий список нецензурних слів та коренів (укр/рус) для фільтрації
PROFANITY_ROOTS = [
    r'хуй', r'хуе', r'хуі', r'хуя', r'пізд', r'пизд', r'єбл', r'ебл', r'бля', 
    r'сук', r'гондо', r'ганд', r'мудак', r'мудил', r'дроч', r'курв', r'бляд', 
    r'член', r'залуп', r'уйоб', r'уеб', r'охує', r'охуе', r'пидар', r'підар'
]

PROFANITY_RE = re.compile(r'\b(' + '|'.join(PROFANITY_ROOTS) + r')\w*\b', re.IGNORECASE)

def validate_text(text: str) -> tuple[bool, str]:
    """
    Перевіряє текст на наявність нецензурної лексики та російської мови.
    Повертає (True, "") якщо все добре, або (False, "помилка") якщо є порушення.
    """
    if not text:
        return True, ""
        
    text_lower = text.lower()
    
    # 1. Перевірка на російські літери
    if RU_LETTERS_RE.search(text):
        return False, "Будь ласка, пишіть відгук українською мовою. Наш портал підтримує виключно державну мову."
        
    # 2. Перевірка на популярні російські слова (розділяємо текст на слова)
    words = set(re.findall(r'\b[a-zа-яіїєґ\']+\b', text_lower))
    if RU_WORDS.intersection(words):
        return False, "Будь ласка, пишіть відгук українською мовою. Наш портал підтримує виключно державну мову."
        
    # 3. Перевірка на нецензурну лексику
    # Спочатку шукаємо точні збіги коренів
    for root in PROFANITY_ROOTS:
        if re.search(root, text_lower):
            return False, "Ваш відгук містить неприпустиму лексику. Будь ласка, відредагуйте текст і висловлюйтеся культурно."
            
    return True, ""
